from openai import OpenAI
from config import GROQ_API_KEY, GROQ_BASE_URL


async def generate_telegram_post(vacancy_info: str) -> str:
    """Генерирует пост для Telegram на основе информации о вакансии"""
    
    client = OpenAI(
        api_key=GROQ_API_KEY,
        base_url=GROQ_BASE_URL
    )
    
#     prompt = f"""
# На основе следующей информации о вакансии создай привлекательный пост для Telegram-канала о работе.

# Требования к посту:
# - Используй эмодзи для визуального оформления
# - Выдели ключевые преимущества вакансии
# - Сделай акцент на зарплате (если указана)
# - Добавь призыв к действию
# - Длина поста: 150-300 слов
# - Тон: профессиональный, но дружелюбный

# Информация о вакансии:
# {vacancy_info}

# Создай готовый пост:
# """

    promt = f"""

    Ты — эксперт по созданию вакансий для Telegram-каналов о работе. Твоя задача — на основе предоставленной информации о вакансии создать максимально привлекательный, готовый к публикации пост в Telegram.

Обязательная структура поста (строго соблюдай этот порядок блоков, не меняй последовательность):

1. Заголовок должности в верхнем регистре + эмодзи профессии слева  
   Пример: 👨‍💻 SENIOR JAVA DEVELOPER   или   👨‍✈️ ВЕДУЩИЙ ИНЖЕНЕР

2. Самая яркая строка про зарплату (если указана) — крупно, с эмодзи 💰  
   Пример: 💰 ЗАРПЛАТА ДО 315 000 РУБЛЕЙ!   или   💰 от 180 000 до 350 000 ₽ на руки

3. Блок «ПОЧЕМУ МЫ» или «ЧЕМ МЫ КРУТЫ» с 3–6 короткими преимуществами компании (эмодзи слева от каждого пункта)

4. Блок «ТВОИ ОСНОВНЫЕ ЗАДАЧИ» или «ЧТО ДЕЛАТЬ» — 4–7 ключевых обязанностей, каждая с новой строки, эмодзи 🛠 или аналогичный слева

5. Блок «МЫ ИЩЕМ ТЕБЯ, ЕСЛИ ТЫ» или «ТРЕБУЕМЫЕ НАВЫКИ» — обязательные и желательные требования, каждое с новой строки, эмодзи 🎯 или ✅ слева. Обязательные пункты пиши ЗАГЛАВНЫМИ или с пометкой (ОБЯЗАТЕЛЬНО!)

6. Блок «ЧТО МЫ ПРЕДЛАГАЕМ» — полный список условий, льгот, бонусов (зарплата повторяется здесь подробнее, график, ДМС, отпуск, релокация и т.д.), эмодзи слева от каждого пункта

7. Финальный призыв к действию с эмодзи 👉🏼 или 🔥  
   Обязательно: «Ссылка на вакансию» + полная ссылка[](https://...)  
   Можно добавить: «Откликайся скорее — разберут быстро!» или «Ждём твой отклик в течение 48 часов»

Правила оформления:
- Используй эмодзи в начале каждого крупного блока и слева от пунктов (не больше 1–2 на строку)
- Выделяй важное **жирным** (должность, зарплата, слово ОБЯЗАТЕЛЬНО!)
- Длина поста — 180–320 слов
- Тон — уверенный, профессиональный, но тёплый и дружелюбный (никакого канцелярита)
- Пиши от второго лица («тебе», «ты», «твои задачи»)
- Не добавляй лишних вступлений и заключений вне указанной структуры
- Не придумывай информацию, которой нет в описании вакансии
- Если какого-то блока информации нет — пропусти его или сделай очень коротким

Информация о вакансии:
{vacancy_info}

Выдай ТОЛЬКО готовый пост для Telegram — без каких-либо комментариев, пояснений и кавычек перед/после.

    """
    
    response = client.chat.completions.create(
        model="llama-3.3-70b-versatile",  # Быстрая и качественная модель
        messages=[
            {
                "role": "system", 
                "content": "Ты помощник, который создаёт привлекательные посты для Telegram-канала о работе. Пиши на русском языке."
            },
            {
                "role": "user", 
                "content": prompt
            }
        ],
        max_tokens=1000,
        temperature=0.7
    )
    
    return response.choices[0].message.content
